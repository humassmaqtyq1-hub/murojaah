export function juzOf(s: number, a: number): number {
  let j = 1;
  for (let i = 0; i < JUZ.length; i++) {
    const [js, ja] = JUZ[i];
    if (s > js || (s === js && a >= ja)) j = i + 1;
    else break;
  }
  return j;
}

export function surahsInJuz(j: number): { no: number; start: number }[] {
  const [s1, a1] = JUZ[j - 1];
  const next = JUZ[j];
  const out: { no: number; start: number }[] = [];
  const last = next ? (next[1] === 1 ? next[0] - 1 : next[0]) : 114;
  for (let s = s1; s <= last; s++) {
    out.push({ no: s, start: s === s1 ? a1 : 1 });
  }
  return out;
}

